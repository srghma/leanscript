#!/usr/bin/env python3
"""Generate `LeanScript/TermElab/ToTerm/ExternTable.lean` from the catalogue of externs.

Every active entry of the catalogue (`LeanScript/LeanInitPureExterns/*.lean`) ends with a
comment naming the Lean function it stands for:

    | lean_nat_add : PreludeExtern [nat, nat] nat -- Nat.add

The table maps that function to the entry, for `#leanscript_to_term`, which translates a
call of the function to a call of the extern.  Run it again after changing the catalogue.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAT = os.path.join(ROOT, 'LeanScript', 'LeanInitPureExterns')
OUT = os.path.join(ROOT, 'LeanScript', 'TermElab', 'ToTerm', 'ExternTable.lean')

rows, seen = [], set()
for th in ['Core', 'FixedWidth', 'String', 'Float']:
    for line in open(os.path.join(CAT, th + '.lean')):
        m = re.match(r'^\s*\| (\S+) : .* -- (\S+)', line)
        if not m:
            continue
        entry, fn = m.groups()
        if fn.startswith('_private') or fn in seen:
            continue
        seen.add(fn)
        rows.append((fn, entry))

body = ',\n'.join(f'   (`{fn}, `{entry})' for fn, entry in rows)
open(OUT, 'w').write(f'''module

public meta import Lean.Data.NameMap

@[expose] public section

meta section

set_option autoImplicit false

/-!
# The Lean functions of the externs

Generated by `scripts/gen_extern_table.py` from the catalogue of externs
(`LeanScript.LeanInitPureExterns`); do not edit.  `externTable` maps every Lean function that
an entry of the catalogue stands for to that entry (`Nat.add ↦ lean_nat_add`, the shorthand
`LeanInitPureExtern.lean_nat_add`): `#leanscript_to_term` translates a call of the function
to a call of the extern.
-/

namespace LeanScript.Gen

open Lean

/-- The Lean function of every entry of the catalogue of externs, and the entry. -/
def externTableList : List (Name × Name) :=
  [{body.lstrip()}]

/-- `externTableList`, as a map from the Lean function to the entry. -/
def externTable : NameMap Name :=
  externTableList.foldl (fun m (f, e) => m.insert f e) {{}}

end LeanScript.Gen

end
''')
print(len(rows))
